import { Info } from "lucide-react";

import { Recommendations } from "@/components/insight-panels";
import { PageHeader } from "@/components/shell/app-shell";
import { parseDays, RangePicker } from "@/components/range-picker";
import { Badge } from "@/components/ui/badge";
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card";
import { latestInsights } from "@/lib/growth";
import { formatDateTime } from "@/lib/time";
import { serviceInfo } from "@/lib/ui-labels";

import { RefreshInsightsButton } from "./refresh-button";

export const dynamic = "force-dynamic";
export const metadata = { title: "Growth insights — Content Engine" };

const CHANNEL_LABEL = { website: "Website", "google-business": "Google Business" };

export default async function InsightsPage({ searchParams }) {
  const days = parseDays((await searchParams)?.days);
  const insights = await latestInsights();

  return (
    <>
      <PageHeader
        title="Growth insights"
        description="AI reads your stats and traffic and tells you what to do next."
        actions={
          <>
            <RangePicker days={days} basePath="/insights" />
            <RefreshInsightsButton days={days} hasInsights={Boolean(insights)} />
          </>
        }
      />

      {!insights ? (
        <Card>
          <CardHeader>
            <CardTitle>No insights yet</CardTitle>
            <CardDescription>
              Generate them to get a plain-English read of what&apos;s working, a prioritised to-do list and content ideas. Takes about 20 seconds.
            </CardDescription>
          </CardHeader>
        </Card>
      ) : (
        <>
          <Card>
            <CardHeader>
              <CardTitle>The read</CardTitle>
              <CardDescription>
                Last {insights.days} days · generated {formatDateTime(insights.createdAt)}
                {insights.createdBy ? ` by ${insights.createdBy}` : ""}
              </CardDescription>
            </CardHeader>
            <CardContent className="flex flex-col gap-3">
              <p className="max-w-[75ch] text-sm leading-7 text-gray-700">{insights.summary}</p>
              <div className="flex flex-wrap gap-2">
                {insights.simulated && <Badge variant="secondary">Based on simulated sandbox stats</Badge>}
                {!insights.websiteConnected && <Badge variant="secondary">Website data not connected</Badge>}
              </div>
            </CardContent>
          </Card>

          <section className="flex flex-col gap-3" aria-labelledby="todo-heading">
            <h2 id="todo-heading" className="text-lg font-semibold text-gray-900">What to do next</h2>
            <Recommendations items={insights.recommendations} />
          </section>

          <Card>
            <CardHeader>
              <CardTitle>Content ideas</CardTitle>
              <CardDescription>Jobs worth photographing and writing up next.</CardDescription>
            </CardHeader>
            <CardContent>
              <ul className="grid gap-3 md:grid-cols-2">
                {insights.contentIdeas.map((idea) => (
                  <li key={idea.idea} className="flex flex-col gap-1.5 rounded-lg bg-gray-50 p-4">
                    <Badge variant="secondary">{serviceInfo(idea.channel).label === idea.channel ? CHANNEL_LABEL[idea.channel] || idea.channel : serviceInfo(idea.channel).label}</Badge>
                    <p className="text-sm font-semibold text-gray-900">{idea.idea}</p>
                    <p className="text-sm text-gray-600">{idea.why}</p>
                  </li>
                ))}
              </ul>
            </CardContent>
          </Card>
        </>
      )}

      <p className="flex items-start gap-2 text-xs text-gray-500">
        <Info className="mt-0.5 size-3.5 shrink-0" />
        Advice is generated by AI from the numbers available. It&apos;s a starting point, not a guarantee — check it against what you know about your clients.
      </p>
    </>
  );
}
